from datetime import datetime, timezone

from app.services import storage


def test_local_inventory_lists_only_generated_regular_invoice_objects(tmp_path, monkeypatch):
    monkeypatch.setattr(storage.settings, "storage_backend", "local")
    monkeypatch.setattr(storage.settings, "upload_dir", str(tmp_path))
    monkeypatch.setattr(storage, "scan_with_clamav", lambda _content: None)

    stored = storage.store_invoice("tenant-a", ".txt", b"invoice")
    tenant_dir = tmp_path / "tenant-a"
    (tenant_dir / "notes.txt").write_text("not generated by LedgerGate", encoding="utf-8")
    outside = tmp_path / "outside.pdf"
    outside.write_bytes(b"outside")
    (tenant_dir / ("f" * 32 + ".pdf")).symlink_to(outside)

    inventory = storage.list_invoice_objects()

    assert set(inventory) == {stored}
    assert isinstance(inventory[stored], datetime)
    assert inventory[stored].tzinfo == timezone.utc


def test_local_inventory_ignores_symlinked_tenant_directories(tmp_path, monkeypatch):
    monkeypatch.setattr(storage.settings, "storage_backend", "local")
    monkeypatch.setattr(storage.settings, "upload_dir", str(tmp_path))
    outside = tmp_path.parent / (tmp_path.name + "-outside")
    outside.mkdir()
    (outside / ("a" * 32 + ".pdf")).write_bytes(b"outside")
    (tmp_path / "tenant-a").symlink_to(outside, target_is_directory=True)

    assert storage.list_invoice_objects() == {}


def test_s3_inventory_returns_only_generated_invoice_keys(monkeypatch):
    modified = datetime(2026, 11, 1, tzinfo=timezone.utc)

    class FakePaginator:
        def paginate(self, **kwargs):
            assert kwargs == {"Bucket": "ledgergate-private", "Prefix": "tenants/"}
            return [{
                "Contents": [
                    {"Key": "tenants/tenant-a/invoices/" + "a" * 32 + ".pdf", "LastModified": modified},
                    {"Key": "tenants/tenant-a/invoices/not-generated.pdf", "LastModified": modified},
                    {"Key": "tenants/tenant-b/invoices/" + "b" * 32 + ".txt", "LastModified": modified},
                ]
            }]

    class FakeS3:
        def get_paginator(self, name):
            assert name == "list_objects_v2"
            return FakePaginator()

    monkeypatch.setattr(storage.settings, "storage_backend", "s3")
    monkeypatch.setattr(storage.settings, "s3_bucket", "ledgergate-private")
    monkeypatch.setattr(storage, "_s3_client", lambda: FakeS3())

    inventory = storage.list_invoice_objects()

    assert set(inventory) == {
        "s3://ledgergate-private/tenants/tenant-a/invoices/" + "a" * 32 + ".pdf",
        "s3://ledgergate-private/tenants/tenant-b/invoices/" + "b" * 32 + ".txt",
    }
